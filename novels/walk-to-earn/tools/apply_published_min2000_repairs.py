def body_chars(text: str) -> int:
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    first = next(i for i, line in enumerate(lines) if line.strip())
    body = "\n".join(lines[first + 1:]).strip()
    return len(re.sub(r"\s", "", body))


def main() -> int:
    changed = []
    for number, block in BLOCKS.items():
        path = CHAPTERS / f"chapter-{number:03d}.md"
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n").rstrip()
        before = body_chars(text)
        if before >= 2000:
            print(f"SKIP ch{number}: already {before}")
            continue
        marker = f"<!-- min2000-repair-ch{number} -->"
        if marker in text:
            print(f"SKIP ch{number}: repair marker already present")
            continue
        repaired = text + "\n\n" + marker + "\n" + block.strip() + "\n"
        after = body_chars(repaired)
        if after < 2000:
            raise RuntimeError(f"ch{number} still short after repair: {before} -> {after}")
        path.write_text(repaired, encoding="utf-8")
        changed.append((number, before, after))
        print(f"REPAIRED ch{number}: {before} -> {after}")

    print(f"changed={len(changed)}")
    return 0

