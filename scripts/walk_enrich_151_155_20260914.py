def main() -> int:
    changed = []
    for number, (anchor, addition) in PATCHES.items():
        path = CHAPTERS / f"chapter-{number}.md"
        text = path.read_text(encoding="utf-8")
        first_line = addition.splitlines()[0]
        if first_line in text:
            continue
        if anchor not in text:
            raise SystemExit(f"chapter {number}: anchor not found")
        text = text.replace(anchor, addition + anchor, 1)
        path.write_text(text, encoding="utf-8")
        changed.append(number)
    print("ENRICHED=" + ",".join(map(str, changed)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
