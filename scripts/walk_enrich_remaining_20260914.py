def main() -> int:
    changed = []
    for number, (anchor, addition) in sorted(PATCHES.items()):
        path = CHAPTERS / f"chapter-{number}.md"
        text = path.read_text(encoding="utf-8")
        first = addition.splitlines()[0]
        if first in text:
            continue
        if anchor not in text:
            raise SystemExit(f"chapter {number}: anchor not found")
        path.write_text(text.replace(anchor, addition + anchor, 1), encoding="utf-8")
        changed.append(number)
    print("ENRICHED=" + ",".join(map(str, changed)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
