changed = []
for chapter, replacements in FIXES.items():
    path = CH / f"chapter-{chapter:03d}.md"
    text = path.read_text(encoding="utf-8")
    original = text
    for old, new in replacements:
        count = text.count(old)
        if count != 1:
            raise SystemExit(f"chapter {chapter}: expected exactly one match for {old!r}, got {count}")
        text = text.replace(old, new, 1)
    if text != original:
        path.write_text(text, encoding="utf-8")
        changed.append(chapter)

print("COLDREAD_FIXES_APPLIED", changed)
if sorted(changed) != sorted(FIXES):
    raise SystemExit(f"unexpected changed set: {changed}")
