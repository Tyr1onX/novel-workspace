from pathlib import Path

ROOT = Path('novels/endless-rail/chapters')


def insert(path: str, anchor: str, addition: str) -> None:
    p = Path(path)
    text = p.read_text(encoding='utf-8')
    if anchor not in text:
        raise SystemExit(f'anchor missing in {path}: {anchor[:60]}')
    text = text.replace(anchor, addition.rstrip() + '\n\n' + anchor, 1)
    p.write_text(text, encoding='utf-8')


def replace(path: str, old: str, new: str) -> None:
    p = Path(path)
    text = p.read_text(encoding='utf-8')
    if old not in text:
        raise SystemExit(f'replacement missing in {path}: {old}')
    p.write_text(text.replace(old, new, 1), encoding='utf-8')


